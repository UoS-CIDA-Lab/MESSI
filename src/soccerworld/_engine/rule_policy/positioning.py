def deconflict_measured_corner_targets(
    target,
    eligible,
    team_id,
    *,
    r_player,
    hx,
    hy,
):
    """Separate active same-team measured corner targets without moving contests."""

    count = target.shape[0]
    slots = jnp.arange(count, dtype=target.dtype)
    angle = slots * jnp.asarray(GOLDEN_ANGLE, dtype=target.dtype)
    tie = jnp.stack([jnp.cos(angle), jnp.sin(angle)], axis=1)
    eye = jnp.eye(count, dtype=bool)
    pair_on = (
        eligible[:, None]
        & eligible[None, :]
        & (team_id[:, None] == team_id[None, :])
        & (~eye)
    )
    minimum = jnp.asarray(2.0 * r_player, dtype=target.dtype)
    field_limit = jnp.asarray([hx, hy], dtype=target.dtype)

    def separate_once(_, points):
        difference = points[:, None, :] - points[None, :, :]
        distance = jnp.sqrt(
            jnp.sum(difference * difference, axis=2) + SQUARED_EPS
        )
        fallback = tie[:, None, :] - tie[None, :, :]
        raw_direction = jnp.where(
            (distance < COINCIDENT_DISTANCE_EPS)[:, :, None],
            fallback,
            difference,
        )
        direction = raw_direction / (
            _safe_norm(raw_direction, axis=2, keepdims=True) + DIV_EPS
        )
        penetration = jnp.where(
            pair_on,
            jnp.clip(minimum - distance, 0.0, minimum),
            0.0,
        )
        # Over-relaxation clears three-player clusters in the bounded passes
        # instead of approaching one diameter from below.
        correction = 0.55 * jnp.sum(
            penetration[:, :, None] * direction,
            axis=1,
        )
        separated = jnp.clip(points + correction, -field_limit, field_limit)
        changed = eligible & jnp.any(correction != 0.0, axis=1)
        return jnp.where(changed[:, None], separated, points)

    return jax.lax.fori_loop(0, 4, separate_once, target)

