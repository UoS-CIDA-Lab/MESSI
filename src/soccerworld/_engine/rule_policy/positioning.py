def _pair_cost(a, b):
    """z-정규화 좌표계에서의 제곱거리 행렬."""

    def z(v):
        v = np.asarray(v, np.float64)
        return (v - v.mean(0)) / (v.std(0) + 1e-6)

    za, zb = z(a), z(b)
    return np.sum((za[:, None, :] - zb[None, :, :]) ** 2, axis=2)


